@pytest.fixture(autouse=True)
def dedicated_test_weights_only_state():
    """Only this serial CPU test process gets a pristine conversion context.

    Core imports unrelated safe_globals before test collection. Production must
    not clear them; our fixture creates and finally restores an explicit clean
    context instead of weakening the production refusal or faking tensor loads.
    """
    original = torch.serialization.get_safe_globals()
    torch.serialization.clear_safe_globals()
    try:
        yield
    finally:
        torch.serialization.clear_safe_globals()
        torch.serialization.add_safe_globals(original)
        restored = torch.serialization.get_safe_globals()
        assert len(restored) == len(original)
        assert all(any(item is before for before in original) for item in restored)


def _digest(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def checkpoint(tmp_path, *, dtype=torch.float32, protocol=4, empty=True, curvature=False):
    source = tmp_path / "source"
    source.mkdir()
    tensors, entry_map, storage = {}, {}, {}
    generator = torch.Generator().manual_seed(212104)
    for head, out in (("proj_out", 3), ("audio_proj_out", 2)):
        for hop in range(4):
            for factor, shape in (("A", (out, 2)), ("B", (out, out))):
                key = f"transformer.{head}.main.lora_{factor}.{hop}.weight"
                tensors[key] = torch.randn(shape, generator=generator, dtype=dtype)
    if curvature:
        for key in tool._training_keys("h3_4step"):
            tensors[key] = torch.randn((2,), generator=generator, dtype=dtype)
    with (source / "all.distcp").open("wb") as shard:
        shard.write(b"prefix-before-first-record\n")
        for key, tensor in tensors.items():
            chunks = []
            # Real discontiguous source rectangles and a legitimate empty tail.
            for index in range(tensor.shape[-1] if tensor.ndim == 2 else tensor.shape[0]):
                if tensor.ndim == 2:
                    offsets, value = (0, index), tensor[:, index:index + 1]
                    assert not value.is_contiguous()
                else:
                    offsets, value = (index,), tensor[index:index + 1]
                raw = io.BytesIO()
                torch.save(value, raw)
                data = raw.getvalue()
                start = shard.tell()
                shard.write(data)
                chunk = md.ChunkStorageMetadata(torch.Size(offsets), value.size())
                chunks.append(chunk)
                storage[md.MetadataIndex(key, offsets, len(chunks) - 1)] = _StorageInfo("all.distcp", start, len(data))
            if empty:
                offsets = (tensor.shape[0],) + (0,) * (tensor.ndim - 1)
                value = tensor[0:0]
                raw = io.BytesIO()
                torch.save(value, raw)
                start, data = shard.tell(), raw.getvalue()
                shard.write(data)
                chunks.append(md.ChunkStorageMetadata(torch.Size(offsets), value.size()))
                storage[md.MetadataIndex(key, offsets, len(chunks) - 1)] = _StorageInfo("all.distcp", start, len(data))
            entry_map[key] = md.TensorStorageMetadata(md.TensorProperties(dtype=dtype), tensor.size(), chunks)
    metadata = md.Metadata(entry_map, {key: (key,) for key in entry_map}, storage, md.StorageMeta(), "1.0.0")
    (source / ".metadata").write_bytes(pickle.dumps(metadata, protocol=protocol))
    (source / "ptd_info.json").write_text(json.dumps({
        "recipe": "h3_4step", "hop_grid": list(tool.GRIDS["h3_4step"]),
        "base_model": "MiniMaxAI/MiniMax-H3", "base_model_revision": "42ed227ee7df40d41602854ae760620d6eb651fe",
    }), encoding="utf-8")
    manifest = tmp_path / "manifest.json"
    update_manifest(source, manifest)
    return source, tensors, metadata, manifest


def update_manifest(source, manifest):
    manifest.write_text(json.dumps({"files": [
        {"file": str(path.relative_to(source).as_posix()), "bytes": path.stat().st_size, "sha256": _digest(path)}
        for path in sorted(source.iterdir()) if path.is_file()
    ]}), encoding="utf-8")


def replace_metadata(source, metadata, manifest=None):
    (source / ".metadata").write_bytes(pickle.dumps(metadata, protocol=4))
    if manifest:
        update_manifest(source, manifest)


@pytest.mark.parametrize("protocol,dtype", [(4, torch.float32), (5, torch.float64), (4, torch.bfloat16)])
def test_real_bounded_Torch_records_stream_exact_bytes_and_runtime_metadata(tmp_path, monkeypatch, protocol, dtype):
    source, expected, _, manifest = checkpoint(tmp_path, protocol=protocol, dtype=dtype, curvature=True)
    metadata, selected, plan = tool.prepare(source, "h3_4step")
    assert plan["weights_only_tensor_reads"] == 0
    assert metadata.syntax["protocol"] == protocol
    assert len(plan["excluded_training_keys"]) == 16
    assert plan["topology"] == {"blocks": 0, "refiners": 0, "pairs": 8}
    assert all(any(0 in c.sizes for c in item.chunks) for item in selected.values())
    rebuilt = safe.to_torch_metadata(metadata)
    assert isinstance(rebuilt, md.Metadata)
    assert set(rebuilt.state_dict_metadata) == set(expected)
    monkeypatch.setattr(FileSystemReader, "read_metadata", lambda *a, **k: pytest.fail("unsafe DCP reader was called"))
    monkeypatch.setattr(pickle, "load", lambda *a, **k: pytest.fail("pickle.load was called"))
    monkeypatch.setattr(pickle, "loads", lambda *a, **k: pytest.fail("pickle.loads was called"))
    actual_load, calls = torch.load, []

    def observed(view, **kwargs):
        assert isinstance(view, tool.TensorSlice)
        assert kwargs == {"map_location": "cpu", "weights_only": True}
        calls.append((view.offset, view.length))
        return actual_load(view, **kwargs)

    monkeypatch.setattr(torch, "load", observed)
    output = tmp_path / "new.safetensors"
    report = tool.convert(source, "h3_4step", output, manifest_path=manifest, manifest_root=source)
    loaded = load_file(str(output))
    assert set(loaded) == set(selected)
    for key, tensor in loaded.items():
        torch.testing.assert_close(tensor, expected[key], rtol=0, atol=0)
    assert report["weights_only_tensor_reads"] == len(calls) == sum(len(e.chunks) for e in selected.values())
    assert report["output_sha256"] == _digest(output)
    assert report["source_integrity"]["files"]
    assert report["GPU_initialized"] is False and not torch.cuda.is_initialized()


def test_default_CLI_imports_no_Torch_reads_no_tensors_and_never_overwrites_report(tmp_path):
    source, _, _, _ = checkpoint(tmp_path)
    report = tmp_path / "prepared.json"
    command = (
        "import runpy,sys; m=runpy.run_path(sys.argv[1],run_name='safe_import_only');"
        "m['main'](['--source',sys.argv[2],'--recipe','h3_4step','--report',sys.argv[3]]);"
        "assert 'torch' not in sys.modules"
    )
    result = subprocess.run([sys.executable, "-I", "-c", command, str(ROOT / "tools" / "convert_h21_ptd_safe.py"), str(source), str(report)], capture_output=True, text=True, timeout=30)
    assert result.returncode == 0, result.stderr
    saved = json.loads(report.read_text())
    assert saved["weights_only_tensor_reads"] == 0 and saved["status"] == "prepared_tensor_reads_not_executed"
    before = report.read_bytes()
    with pytest.raises(SystemExit):
        tool.main(["--source", str(source), "--recipe", "h3_4step", "--report", str(report)])
    assert report.read_bytes() == before


