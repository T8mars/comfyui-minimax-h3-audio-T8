@pytest.mark.parametrize("fault", ["missing_storage", "overlap", "gap", "out_of_bounds", "serialized_overlap", "short_file", "path_escape", "planner_object"])
def test_true_storage_and_geometry_errors_are_not_hidden(tmp_path, fault):
    source, _, metadata, _ = checkpoint(tmp_path)
    entry = next(iter(metadata.state_dict_metadata.values()))
    storage = next(iter(metadata.storage_data.values()))
    if fault == "missing_storage":
        metadata.storage_data.pop(next(iter(metadata.storage_data)))
    elif fault == "overlap":
        entry.chunks[0].sizes = torch.Size((2, 2))
    elif fault == "gap":
        entry.chunks[0].sizes = torch.Size((0, 2))
    elif fault == "out_of_bounds":
        entry.chunks[0].sizes = torch.Size((999, 2))
    elif fault == "serialized_overlap":
        list(metadata.storage_data.values())[1].offset = storage.offset
    elif fault == "short_file":
        storage.length = (source / "all.distcp").stat().st_size + 1
    elif fault == "path_escape":
        storage.relative_path = "../all.distcp"
    else:
        metadata.planner_data[next(iter(metadata.planner_data))] = ("different-entry",)
    replace_metadata(source, metadata)
    with pytest.raises(ValueError):
        tool.prepare(source, "h3_4step")


def test_inference_unknown_keys_and_incomplete_scaffolds_are_not_silently_dropped(tmp_path):
    source, _, metadata, _ = checkpoint(tmp_path, curvature=True)
    removed = next(k for k in metadata.state_dict_metadata if "fan_chead" in k)
    # All stored records still need valid targets; removal is a true storage error.
    metadata.state_dict_metadata.pop(removed)
    metadata.planner_data.pop(removed)
    metadata.storage_data = {k: v for k, v in metadata.storage_data.items() if k.fqn != removed}
    replace_metadata(source, metadata)
    with pytest.raises(ValueError, match="Incomplete published training"):
        tool.prepare(source, "h3_4step")


@pytest.mark.parametrize("fault", ["bad_hash", "missing_shard", "outside_manifest", "existing_output", "output_inside_source"])
def test_manifest_paths_bytes_and_no_overwrite_before_any_tensor_load(tmp_path, monkeypatch, fault):
    source, _, _, manifest = checkpoint(tmp_path)
    output = tmp_path / "new.safetensors"
    original_output = b"original-user-data"
    contents = json.loads(manifest.read_text())
    if fault == "bad_hash":
        contents["files"][0]["sha256"] = "0" * 64
    elif fault == "missing_shard":
        contents["files"] = [x for x in contents["files"] if x["file"] != "all.distcp"]
    elif fault == "outside_manifest":
        contents["files"][0]["file"] = "../elsewhere"
    elif fault == "existing_output":
        output.write_bytes(original_output)
    else:
        output = source / "new.safetensors"
    manifest.write_text(json.dumps(contents))
    monkeypatch.setattr(torch, "load", lambda *a, **k: pytest.fail("tensor was read before verification"))
    with pytest.raises((ValueError, FileExistsError)):
        tool.convert(source, "h3_4step", output, manifest_path=manifest, manifest_root=source)
    if fault == "existing_output":
        assert output.read_bytes() == original_output
    else:
        assert not output.exists()
    assert not list(tmp_path.glob("*.partial"))


def test_unsafe_Torch_safe_globals_not_cleared_or_used(tmp_path):
    source, _, _, manifest = checkpoint(tmp_path)
    before = torch.serialization.get_safe_globals()
    with torch.serialization.safe_globals([Payload]):
        with pytest.raises(ValueError, match="safe_globals"):
            tool.convert(source, "h3_4step", tmp_path / "new.safetensors", manifest_path=manifest, manifest_root=source)
    after = torch.serialization.get_safe_globals()
    assert len(after) == len(before)
    assert all(any(item is original for original in before) for item in after)


def test_weights_only_rejects_arbitrary_shard_object_and_cleans_partial(tmp_path):
    source, _, metadata, manifest = checkpoint(tmp_path)
    marker = tmp_path / "no-shard-callback"
    target_index = next(iter(metadata.storage_data))
    target = metadata.storage_data[target_index]
    raw = io.BytesIO()
    torch.save(Payload(marker), raw)
    # A new exact record, no overlapping byte offsets, still a hostile tensor.
    with (source / "all.distcp").open("ab") as stream:
        target.offset = stream.tell()
        stream.write(raw.getvalue())
        target.length = len(raw.getvalue())
    replace_metadata(source, metadata, manifest)
    output = tmp_path / "new.safetensors"
    with pytest.raises(pickle.UnpicklingError):
        tool.convert(source, "h3_4step", output, manifest_path=manifest, manifest_root=source)
    assert not marker.exists() and not output.exists()
    assert not list(tmp_path.glob("*.partial"))


@pytest.mark.parametrize("fault", ["nan", "shape", "finite_large_float64"])
def test_actual_loaded_shape_nonfinite_and_large_finite_FP64(tmp_path, fault):
    dtype = torch.float64 if fault == "finite_large_float64" else torch.float32
    source, expected, metadata, manifest = checkpoint(tmp_path, dtype=dtype)
    index = next(iter(metadata.storage_data))
    item = metadata.storage_data[index]
    chunk = metadata.state_dict_metadata[index.fqn].chunks[index.index]
    value = torch.full(tuple(chunk.sizes), 1e200 if dtype == torch.float64 else 0, dtype=dtype)
    if fault == "nan":
        value[0, 0] = float("nan")
    elif fault == "shape":
        value = torch.zeros((1, 1), dtype=dtype)
    else:
        expected[index.fqn][:, 0:1] = value
    raw = io.BytesIO()
    torch.save(value, raw)
    with (source / "all.distcp").open("ab") as stream:
        item.offset, item.length = stream.tell(), len(raw.getvalue())
        stream.write(raw.getvalue())
    replace_metadata(source, metadata, manifest)
    output = tmp_path / "new.safetensors"
    if fault == "finite_large_float64":
        tool.convert(source, "h3_4step", output, manifest_path=manifest, manifest_root=source)
        for key, value in load_file(str(output)).items():
            torch.testing.assert_close(value, expected[key], rtol=0, atol=0)
    else:
        with pytest.raises(ValueError, match="Non-finite|differs from verified"):
            tool.convert(source, "h3_4step", output, manifest_path=manifest, manifest_root=source)
        assert not output.exists() and not list(tmp_path.glob("*.partial"))


def test_last_tensor_read_cannot_hide_earlier_source_byte_mutation(tmp_path, monkeypatch):
    source, _, _, manifest = checkpoint(tmp_path)
    metadata, selected, _ = tool.prepare(source, "h3_4step")
    expected_calls = sum(len(t.chunks) for t in selected.values())
    actual_load, calls = torch.load, []

    def changed(view, **kwargs):
        value = actual_load(view, **kwargs)
        calls.append(1)
        if len(calls) == expected_calls:
            with (source / "all.distcp").open("r+b") as stream:
                stream.write(b"X")
        return value

    monkeypatch.setattr(torch, "load", changed)
    output = tmp_path / "new.safetensors"
    with pytest.raises(ValueError, match="Manifest content mismatch"):
        tool.convert(source, "h3_4step", output, manifest_path=manifest, manifest_root=source)
    assert len(calls) == expected_calls and not output.exists()
    assert metadata.sha256 == _digest(source / ".metadata")


