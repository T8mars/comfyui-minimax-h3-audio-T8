class Payload:
    def __init__(self, marker):
        self.marker = marker

    def __reduce__(self):
        return eval, (f"__import__('pathlib').Path({str(self.marker)!r}).write_text('EXECUTED')",)


def test_malicious_GLOBAL_REDUCE_never_imported_or_executed(tmp_path):
    marker = tmp_path / "must-not-exist"
    with pytest.raises(safe.UnsafeMetadata, match="Unsupported symbol"):
        safe.decode_inert(pickle.dumps(Payload(marker), protocol=4))
    assert not marker.exists()


def test_trusted_metadata_bridge_preserves_actual_literal_properties(tmp_path):
    source, _, original, _ = checkpoint(tmp_path)
    entry = next(iter(original.state_dict_metadata.values()))
    entry.properties.requires_grad = True
    entry.properties.pin_memory = True
    replace_metadata(source, original)
    loaded = safe.read_metadata(source / ".metadata")
    rebuilt = safe.to_torch_metadata(loaded)
    props = next(iter(rebuilt.state_dict_metadata.values())).properties
    assert props.requires_grad is True and props.pin_memory is True
    assert not torch.cuda.is_initialized()


